/*
# Allow client-generated trade identity on insert

Trade IDs are generated by the existing journal UI and are not ownership fields.
Clients may provide trade_id when creating a trade, but the column remains absent
from UPDATE privileges so it cannot be changed later. user_id and timestamps still
come from database defaults and remain protected.
*/

REVOKE INSERT ON trades FROM authenticated;
GRANT INSERT (
  trade_id, pair, type, entry_price, exit_price, lot_size, pnl, status, session,
  timestamp, notes, risk_percent, ai_feedback, is_analyzing
) ON trades TO authenticated;
